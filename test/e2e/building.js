import { sleep } from './browser.js';

export async function building({ cdp, ev, down, up, until, open, check, state }) {
  await open('#');
  await ev(`document.querySelector('#build-level').click()`);
  check('builder opens', await until(async () => ev(`document.body.classList.contains('editing')`), 6000));
  await sleep(600);
  const tabs = await ev(`[...document.querySelectorAll('#edit-tabs button')].map(b => b.textContent)`);
  const clickTab = name => ev(`[...document.querySelectorAll('#edit-tabs button')].find(b => b.textContent === ${JSON.stringify(name)})?.click()`);
  const pickBlock = id => ev(`document.querySelector('#edit-blocks button[data-block="${id}"]')?.click() ?? !!document.querySelector('#edit-blocks button[data-block="${id}"]')`);
  const cell = async (c, r) => { const v = await ev(`(() => { const b = document.querySelector('#game').getBoundingClientRect(); return { left: b.left, top: b.top, scale: b.width / 960, cam: shiftform.camera() }; })()`); return { x: v.left + (c + 0.5) * 30 * v.scale, y: v.top + ((r + 0.5) * 30 - v.cam) * v.scale }; };
  const mouse = (type, p, extra = {}) => cdp('Input.dispatchMouseEvent', { type, x: p.x, y: p.y, button: 'left', buttons: type === 'mouseReleased' ? 0 : 1, clickCount: 1, ...extra });
  const drag = async (a, b) => { const p = await cell(...a), q = await cell(...b); await mouse('mouseMoved', p, { button: 'none', buttons: 0 }); await mouse('mousePressed', p); await sleep(40); await mouse('mouseMoved', q); await sleep(40); await mouse('mouseReleased', q); await sleep(120); };
  const bp = () => ev('shiftform.editor().blueprint');
  const bRows = (await bp()).rows, base = bRows - 2;
  check('builder has block tabs', tabs.length > 2, tabs.join(','));
  await clickTab('Ground');
  await sleep(100);
  const hasWater = await pickBlock('water');
  check('water is in the Ground tab', hasWater);
  await drag([10, base], [15, base - 3]);
  let tiles = (await bp()).tiles;
  const waterAt = (c, r) => tiles[r * 32 + c] === 3;
  check('dragging paints water square by square', waterAt(10, base) && waterAt(15, base - 3) && waterAt(12, base - 1) && !waterAt(16, base), '');
  await pickBlock('rock').catch(() => {});
  await pickBlock('rock');
  await drag([12, base - 3], [13, base - 3]);
  tiles = (await bp()).tiles;
  check('rock paints over water', tiles[(base - 3) * 32 + 12] === 1);
  const waters = await ev(`shiftform.editor().level().objects.filter(o => o.type === 'water').map(o => ({ c: o.x / 30, r: o.y / 30, w: o.w / 30, h: o.h / 30, surface: o.surface }))`);
  check('the game works out the surface around rock', waters.some(w => w.surface === false) && waters.some(w => w.surface === true), JSON.stringify(waters));
  await clickTab('Momentum'); await sleep(100);
  await pickBlock('pendulum');
  await drag([22, base - 8], [22, base - 8]);
  await ev(`document.querySelector('#edit-timing').click()`);
  check('timing tool lights up', await ev(`document.querySelector('#edit-timing').classList.contains('on')`));
  const timedItem = () => bp().then(b => b.items.find(i => i.b === 'pendulum'));
  const before = await timedItem();
  check('pendulum was placed', before, JSON.stringify(before));
  await drag([22, base - 8], [22, base - 8]);
  const stepped = await timedItem();
  check('tapping with Timing steps the start position', stepped?.p === 1, `p=${stepped?.p}`);
  const phase1 = await ev(`shiftform.editor().level().objects.find(o => o.type === 'hook').phase`);
  check('the level uses that start position', phase1 === 15, `phase ${phase1}`);
  await ev(`document.querySelector('#edit-undo').click()`); await sleep(100);
  check('undo reverts the timing step', (await timedItem())?.p === undefined, `p=${(await timedItem())?.p}`);
  await ev(`document.querySelector('#edit-redo').click()`); await sleep(100);
  check('redo restores it', (await timedItem())?.p === 1);
  const start2 = (await bp()).items.find(i => i.b === 'start');
  await ev(`document.querySelector('#edit-test').click()`);
  check('test mode runs the level', await until(async () => { const s = await ev('shiftform.state()'); return s?.phase === 'play' && !(await ev(`document.body.classList.contains('testing')`)) === false; }, 6000));
  await sleep(400);
  const surfaceY = (base - 3) * 30;
  await ev(`shiftform.warp(${11 * 30 + 5}, ${(base + 1) * 30 - 26})`);
  await sleep(300);
  let highest = 1e9, spun = false;
  const t0 = Date.now();
  while (Date.now() - t0 < 3600) { await down('Space'); await sleep(90); await up('Space'); await sleep(90); const s = await state(); highest = Math.min(highest, s.y + 26); }
  check('swimming rises to the top of painted water', highest < surfaceY + 26, `feet ${Math.round(highest)}, surface ${surfaceY}`);
  check('you cannot leap out of painted water', surfaceY - highest < 22, `rose ${Math.round(surfaceY - highest)} px above the surface`);
  await ev(`document.querySelector('#edit-test').click()`);
  await sleep(500);
  check('leaving test mode returns to the builder', await ev(`!document.body.classList.contains('testing')`));
}
